  constructor(
    plan: PlannedEncounter[] = generateEncounterPlan(15, { seed: "preview" }),
    heroId = "bimo",
  ) {
    super("AdventureScene");
    this.plan =
      plan.length > 0 ? plan : generateEncounterPlan(15, { seed: "preview" });
    this.layout = generateLevelLayout(this.plan.length);
    this.worldWidth = this.layout.worldWidth;
    this.heroId = ["rara", "bimo", "tari"].includes(heroId) ? heroId : "bimo";
  }

  preload() {
    // Reuse the exact asset paths used by the character preview and battle UI.
    const hero = getHeroById(this.heroId);
    Object.entries(hero.assets).forEach(([pose, assetPath]) => {
      this.load.image(`adventure-hero-${pose}`, assetPath);
    });

    // Load the four poses of every monster in this run's plan, from the
    // monster config's asset paths. Monsters whose artwork arrives in
    // Sprint D simply fail to load here; createEncounters then falls back
    // to the generated tier graphics (see monsterTextures).
    const loadedMonsterIds = new Set<string>();
    this.plan.forEach((encounter) => {
      if (loadedMonsterIds.has(encounter.monsterId)) return;
      loadedMonsterIds.add(encounter.monsterId);
      const definition = getAdventureMonsterById(encounter.monsterId);
      (["idle", "attack", "hurt", "defeat"] as const).forEach((pose) => {
        this.load.image(
          `adventure-monster-${encounter.monsterId}${pose === "idle" ? "" : `-${pose}`}`,
          definition.assets[pose],
        );
      });
    });

    // Sprint B environment sprites (EnvironmentFactory falls back to the
    // legacy Graphics scenery if any of these fail to load).
    ENVIRONMENT_ASSETS.forEach(({ key, path }) => {
      this.load.image(key, path);
    });

    // Sprint E power-up artwork (procedural textures remain as fallback).
    this.load.image("powerup-heart-art", "/assets/adventure/powerups/heart.webp");
    this.load.image("powerup-shield-art", "/assets/adventure/powerups/shield.webp");
    this.load.image("powerup-star-art", "/assets/adventure/powerups/star.webp");

    // Detailed thorn-bush hazard artwork (the generated red-spike
    // texture remains as fallback).
    this.load.image("hazard-thorn-art", "/assets/adventure/hazard-thorn.webp");

    this.load.on("loaderror", (file: Phaser.Loader.File) => {
      console.error("Adventure asset gagal dimuat:", file.key, file.src);
    });
  }

  create() {
    this.createTextures();
    this.heroIdleTexture = this.textures.exists("adventure-hero-idle")
      ? "adventure-hero-idle"
      : "hero-idle-1";
    // Keep the selected character's real artwork while moving; movement is
    // communicated by body tilt instead of swapping to an attack pose.
    this.heroMoveTexture = this.heroIdleTexture;
    this.heroHurtTexture = this.textures.exists("adventure-hero-hurt")
      ? "adventure-hero-hurt"
      : this.heroIdleTexture;
    this.heroVictoryTexture = this.textures.exists("adventure-hero-victory")
      ? "adventure-hero-victory"
      : this.heroIdleTexture;
    this.heroExhaustedTexture = this.textures.exists("adventure-hero-exhausted")
      ? "adventure-hero-exhausted"
      : this.heroIdleTexture;
    this.environment = new EnvironmentFactory(this);
    this.createWorld();

    this.player = this.physics.add.sprite(120, 430, this.heroIdleTexture);

    this.player.setDisplaySize(76, 88);
    // Anchor the artwork at its feet. All hero sprites (Velo, Theo, Sera)
    // have their feet at the very bottom of the 480px frame — Velo's idle
    // and attack poses were re-aligned in Sprint B — so no per-hero offset
    // is needed and every hero touches the ground the same way.
    this.player.setOrigin(0.5, 1);
    this.player.setCollideWorldBounds(true);
    this.player.setBounce(0.02);
    this.player.setDepth(10);
    // Contact shadow under the hero, repositioned every frame in update().
    this.heroShadow = this.environment.addShadow(120, 560, 62, 0.5);

    this.physics.add.collider(this.player, this.platforms);
    this.createEncounters();
    this.createHazardsAndPowerUps();

    this.cursors = this.input.keyboard!.createCursorKeys();

    this.wasd = {
      left: this.input.keyboard!.addKey(
        Phaser.Input.Keyboard.KeyCodes.A,
      ),
      right: this.input.keyboard!.addKey(
        Phaser.Input.Keyboard.KeyCodes.D,
      ),
      jump: this.input.keyboard!.addKey(
        Phaser.Input.Keyboard.KeyCodes.SPACE,
      ),
    };

    this.cameras.main.setBounds(
      0,
      0,
      this.worldWidth,
      this.worldHeight,
    );

    this.cameras.main.startFollow(
      this.player,
      true,
      0.08,
      0.08,
    );

    this.cameras.main.setDeadzone(180, 90);

    this.game.events.on(
      "virtual-control",
      this.handleVirtualControl,
      this,
    );
    this.input.on("pointerdown", this.unlockAudio, this);
    this.input.keyboard?.on("keydown", this.unlockAudio, this);
    this.game.events.on("resolve-encounter", this.handleResolveEncounter, this);
    this.game.events.on("toggle-sound", this.handleToggleSound, this);
    this.game.events.on("stop-adventure", this.handleStopAdventure, this);

    this.events.once(Phaser.Scenes.Events.SHUTDOWN, () => {
      this.game.events.off(
        "virtual-control",
        this.handleVirtualControl,
        this,
      );
      this.input.off("pointerdown", this.unlockAudio, this);
      this.input.keyboard?.off("keydown", this.unlockAudio, this);
      void this.audioContext?.close();
      this.audioContext = null;
      this.game.events.off("resolve-encounter", this.handleResolveEncounter, this);
      this.game.events.off("toggle-sound", this.handleToggleSound, this);
      this.game.events.off("stop-adventure", this.handleStopAdventure, this);
      this.heroPoseTimer?.remove(false);
      this.heroPoseTimer = null;
    });

    this.createHud();
    this.player.setTexture(this.heroIdleTexture);
  }

  private handleToggleSound(enabled: boolean) {
    this.soundEnabled = enabled;
  }

  private handleVirtualControl(
    direction: VirtualDirection,
    pressed: boolean,
  ) {
    if (pressed) this.unlockAudio();
    this.virtual[direction] = pressed;
  }

  private unlockAudio() {
    if (typeof window === "undefined" || !("AudioContext" in window)) return;

    try {
      this.audioContext ??= new AudioContext();
      if (this.audioContext.state === "suspended") {
        void this.audioContext.resume().catch(() => undefined);
      }
    } catch {
      // Audio is an enhancement; gameplay remains available if it is unsupported.
    }
  }

  private playTone(
    frequency: number,
    duration: number,
    waveform: OscillatorType = "sine",
    volume = 0.045,
  ) {
    const context = this.audioContext;
    if (!this.soundEnabled || !context || context.state !== "running") return;

    const oscillator = context.createOscillator();
    const gain = context.createGain();
    const start = context.currentTime;

    oscillator.type = waveform;
    oscillator.frequency.setValueAtTime(frequency, start);
    gain.gain.setValueAtTime(0.001, start);
    gain.gain.exponentialRampToValueAtTime(volume, start + 0.015);
    gain.gain.exponentialRampToValueAtTime(0.001, start + duration);

    oscillator.connect(gain);
    gain.connect(context.destination);
    oscillator.start(start);
    oscillator.stop(start + duration);
  }

  private playPickupSound() {
    this.playTone(660, 0.1, "sine");
    this.time.delayedCall(85, () => this.playTone(880, 0.13, "sine"));
  }

