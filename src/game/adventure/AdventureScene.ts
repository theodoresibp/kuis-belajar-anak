  /** World layout shared with EnvironmentFactory. Since Sprint C the
   *  geometry comes from the level layout generator (one approach zone
   *  per encounter) instead of hand-placed coordinates. */
  private environmentLayout(): EnvironmentLayout {
    return {
      worldWidth: this.layout.worldWidth,
      worldHeight: this.layout.worldHeight,
      groundTopY: this.layout.groundTopY,
      groundSegments: this.layout.groundSegments,
      avoidX: [
        { x: 120, radius: 90 }, // player spawn
        ...this.layout.encounters.map((spot) => ({ x: spot.x, radius: 120 })),
        ...this.layout.hazards.map((hazard) => ({ x: hazard.x, radius: 55 })),
        ...this.layout.pickups.map((pickup) => ({ x: pickup.x, radius: 50 })),
      ],
    };
  }

  private createWorld() {
    const layout = this.environmentLayout();
    this.environment.createBackdrop(layout);

    this.platforms = this.physics.add.staticGroup();

    // Main ground segments and floating platforms from the generated
    // layout. Physics conventions match the original world: ground
    // centre y 570 (top 556); platform rows from level-layout.ts keep
    // the 445 low row's 9px head clearance under the platforms.
    this.layout.groundSegments.forEach((segment) => {
      this.addPlatform(segment.x, 570, segment.width, "ground");
    });
    this.layout.platforms.forEach((platform) => {
      this.addPlatform(platform.x, platform.y, platform.width, platform.kind);
    });

    this.environment.decorateWorld(layout);

    this.physics.world.setBounds(0, 0, this.worldWidth, this.worldHeight);

    this.environment.createAmbientLife(layout);
  }

  private addPlatform(
    x: number,
    y: number,
    width = 180,
    kind: "ground" | "wood" | "stone" = "wood",
  ) {
    const useArtwork =
      kind === "ground"
        ? this.environment.spritesReady
        : this.environment.platformSpritesReady;
    const pieces = Math.ceil(width / 180);

    for (let i = 0; i < pieces; i += 1) {
      const pieceWidth = Math.min(180, width - i * 180);

      const piece = this.platforms.create(
        x + i * 180 + pieceWidth / 2,
        y,
        "forest-platform",
      ) as Phaser.Physics.Arcade.Sprite;

      piece.setDisplaySize(pieceWidth, 28);
      piece.refreshBody();
      // The physics body stays identical; only the visible texture is
      // replaced by the Sprint B artwork drawn by EnvironmentFactory.
      if (useArtwork) piece.setVisible(false);
    }

    const physicsTopY = y - 14;
    if (kind === "ground") {
      this.environment.createGroundVisual({ x, width }, physicsTopY);
    } else {
      this.environment.createPlatformVisual(x + width / 2, physicsTopY, width, kind);
      this.environment.decoratePlatformTop(x + width / 2, physicsTopY, width);
    }
  }


