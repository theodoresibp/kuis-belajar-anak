type VirtualDirection = "left" | "right" | "jump";

/** What the scene hands to React when an encounter starts: one entry of
 *  the run plan generated by the encounter generator (Sprint C). */
export type AdventureEncounter = PlannedEncounter;

interface MonsterPoseKeys {
  idle: string;
  attack: string;
  hurt: string;
  defeat: string;
  usingFallback: boolean;
}

/** Light tints that tell fallback-graphic monsters apart until Sprint D
 *  delivers their real artwork. */
const FALLBACK_TINTS = [0xffffff, 0xd9f99d, 0xfde68a, 0xfbcfe8, 0xa5f3fc];

/** Sprint F glow colour per important tier (auras, defeat rings). */
const TIER_GLOW: Partial<Record<MonsterTier, number>> = {
  elite: 0xf59e0b,
  "mini-boss": 0xa78bfa,
  "final-boss": 0xf87171,
};

function monsterTintSeed(monsterId: string): number {
  let hash = 0;
  for (let i = 0; i < monsterId.length; i += 1) {
    hash = (hash * 31 + monsterId.charCodeAt(i)) | 0;
  }
  return Math.abs(hash);
}

