  update() {
    if (this.isAdventureStopped) {
      this.player?.setVelocity(0, 0);
      return;
    }

    if (this.encounterPaused) {
      this.player?.setVelocityX(0);
      return;
    }

    if (!this.player?.body || !this.cursors || !this.wasd) {
      return;
    }

    // Sprint F: the next monster notices the hero — a one-time entrance
    // reaction when the hero first comes within 540px.
    const entranceMonster = this.encounterSprites[this.nextEncounterIndex];
    if (
      entranceMonster?.active &&
      !entranceMonster.getData("entered") &&
      Math.abs(entranceMonster.x - this.player.x) < 540
    ) {
      entranceMonster.setData("entered", true);
      this.playMonsterEntrance(entranceMonster);
    }

    // Hero contact shadow: sits on the highest walkable surface at or
    // below the hero's feet, shrinking and fading as the hero rises above
    // it (jumps), hidden over pits where no surface is below.
    if (this.heroShadow) {
      const feet = (this.player.body as Phaser.Physics.Arcade.Body).bottom;
      let surface: number | undefined;
      for (const candidate of this.layout.surfaces) {
        if (
          this.player.x >= candidate.x0 - 6 &&
          this.player.x <= candidate.x1 + 6 &&
          candidate.top >= feet - 8 &&
          (surface === undefined || candidate.top < surface)
        ) {
          surface = candidate.top;
        }
      }
      if (surface === undefined) {
        this.heroShadow.setVisible(false);
      } else {
        const lift = Math.max(0, surface - feet);
        const scale = Phaser.Math.Clamp(1 - lift / 300, 0.35, 1);
        this.heroShadow
          .setVisible(true)
          .setPosition(this.player.x, surface + 5)
          .setDisplaySize(62 * scale, 14 * scale)
          .setAlpha(0.5 * scale);
      }
    }

    const left =
      this.cursors.left.isDown ||
      this.wasd.left.isDown ||
      this.virtual.left;

    const right =
      this.cursors.right.isDown ||
      this.wasd.right.isDown ||
      this.virtual.right;

    const jump =
      Phaser.Input.Keyboard.JustDown(this.cursors.up) ||
      Phaser.Input.Keyboard.JustDown(this.cursors.space) ||
      Phaser.Input.Keyboard.JustDown(this.wasd.jump) ||
      this.virtual.jump;

    // Proximity fallback: start an encounter even if Arcade overlap misses a sprite body.
    const nextMonster = this.encounterSprites[this.nextEncounterIndex];
    if (nextMonster?.active) {
      const playerBounds = this.player.getBounds();
      const monsterBounds = nextMonster.getBounds();
      if (Phaser.Geom.Intersects.RectangleToRectangle(playerBounds, monsterBounds)) {
        this.triggerEncounter(this.player, nextMonster);
        return;
      }
    }

    const body = this.player.body as Phaser.Physics.Arcade.Body;

    if (left === right) {
      this.player.setVelocityX(0);
    } else {
      this.player.setVelocityX(left ? -this.moveSpeed : this.moveSpeed);
      this.player.setFlipX(left);
    }

    if (jump && body.blocked.down) {
      this.player.setVelocityY(this.jumpVelocity);
      this.playTone(480, 0.09, "triangle", 0.035);
    }

    if (jump) {
      this.virtual.jump = false;
    }

    // Jangan timpa pose hurt selama animasi reaksinya masih berlangsung.
    if (!this.heroPoseTimer) {
      if (!body.blocked.down) {
        this.player.setTexture(this.heroMoveTexture);
        this.player.setAngle(Phaser.Math.Clamp(body.velocity.y / 55, -10, 10));
      } else if (left !== right) {
        // Pose idle dipadukan dengan ayunan badan untuk memberi kesan berjalan.
        this.player.setTexture(this.heroIdleTexture);
        this.player.setAngle(Math.sin(this.time.now / 75) * 5);
      } else {
        this.player.setTexture(this.heroIdleTexture);
        this.player.setAngle(0);
      }
    }
  }
